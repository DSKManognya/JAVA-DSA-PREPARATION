public class datatypes {
 public static void main(String[] args){
    byte b = 1;//primitive, range is from -128 to 127, 
    char c = 'a';//primitive, can only store single characters
    boolean bool = true;
    float fl =10.9f;//primitive, range is from 1.4E-45 to 3.4028235E38
    double d = 10.9;//primitive, range is from 4.9E-324 to 1.7976931348623157E308
    int i = 10;//primitive, range is from -2^31 to 2^31-1
    long l = 10L;//primitive, range is from -2^63 to 2^63-1
    short s = 10;//primitive, range is from -32768 to 32767

 }   
}
